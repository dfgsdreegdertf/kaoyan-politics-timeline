function entry(id, name, start, site, { end, fact, exam, place, category = "会议", shortName = name }) {
  const [siteName, coordinates] = sites[site];
  const [year, month, day] = start.split("-").map(Number);
  const [endMonth, endDay] = end ? end.split("-").slice(1).map(Number) : [];
  const dateEnd = end ? (endMonth === month ? `–${endDay}` : `日至${endMonth}月${endDay}`) : "";
  return {
    id, name, year: String(year), start, shortName, site, coordinates, category, fact, exam,
    place: place ?? siteName, siteName, date: `${month}月${day}${dateEnd}日`,
    shortDate: start.slice(5).replace("-", ".")
  };
}

